# Builds src/data/catalog.json and public/exercises/*.jpg from the project's planning files.
# Run: python3 scripts/import_catalog.py <project-files dir>   (needs Pillow for the photos)
import json, os, sys, urllib.request
from io import BytesIO

src = sys.argv[1] if len(sys.argv) > 1 else '/mnt/project-files'
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cat = json.load(open(f'{src}/plans/exercise-catalog.json'))
weights = json.load(open(f'{src}/research/set-weights.json'))
content = json.load(open(f'{src}/plans/muscle-map/content.json'))
workouts = json.load(open(f'{src}/plans/muscle-map/workouts.json'))

groups = []
for g in content['groups']:
    if g['id'] not in workouts['targets']:
        continue
    rec = workouts['recovery'][g['id']]
    groups.append({'id': g['id'], 'name': g['name'], 'desc': g['desc'],
                   'target': workouts['targets'][g['id']], 'restHours': rec['restHours']})

keep = ['id', 'name', 'type', 'equip', 'unit', 'level', 'stress', 'steps', 'cues', 'muscles',
        'rx', 'pattern', 'hardest', 'stretch', 'side', 'alternatives']
exercises = []
for e in cat['exercises']:
    x = {k: e[k] for k in keep if k in e}
    x['credit'] = {g: c for g, c in weights[e['id']].items() if c}  # drop 0 = listed but not credited
    x['img'] = [f"exercises/{e['id']}-{i}.jpg" for i in (0, 1)] if e.get('img') else []
    exercises.append(x)

out = {'source': 'Generated by scripts/import_catalog.py from the project planning files.',
       'patterns': cat['patterns'], 'groups': groups, 'exercises': exercises}
with open(f'{root}/src/data/catalog.json', 'w') as f:
    json.dump(out, f, indent=1)

# Photos: Free Exercise DB (github.com/yuhonas/free-exercise-db, Unlicense), start and end frames, 480px wide.
from PIL import Image
os.makedirs(f'{root}/public/exercises', exist_ok=True)
for e in cat['exercises']:
    if not e.get('img'):
        continue
    for i in (0, 1):
        path = f"{root}/public/exercises/{e['id']}-{i}.jpg"
        if os.path.exists(path):
            continue
        url = f"https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/{e['img']}/{i}.jpg"
        im = Image.open(BytesIO(urllib.request.urlopen(url).read())).convert('RGB')
        im.thumbnail((480, 480))
        im.save(path, quality=78, optimize=True)
print(len(exercises), 'exercises,', len(groups), 'groups')
